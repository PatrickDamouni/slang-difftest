"""slang-difftest: cross-backend differential testing for the Slang compiler.

For each batch:
  1. generate K random well-defined functions (difftest.ast) into one kernel
  2. slangc -> SPIR-V and slangc -> MSL            (compile oracle: crashes,
     internal errors, or rejections of valid code are findings in themselves)
  3. spirv-val on the SPIR-V                        (validity oracle)
  4. run the MSL on native Metal, the SPIR-V on KosmicKrisp and on MoltenVK,
     each in its own process with a timeout          (crash/hang oracle)
  5. compare every output word with the Python reference computed from the
     same AST                                         (value oracle)

Which paths disagree points at a layer:
  metal only            -> Slang's Metal codegen
  kosmickrisp+moltenvk  -> Slang's SPIR-V codegen
  moltenvk only         -> SPIRV-Cross / MoltenVK
  kosmickrisp only      -> KosmicKrisp (Mesa)
  all three GPU paths   -> Apple's Metal compiler, or the reference itself
                           (every GPU path ends in Apple's MSL compiler)

Usage:
  python3 -m difftest.run fuzz --batches 20 --k 32 [--family shift] [--seed 1]
  python3 -m difftest.run selftest
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import re
import shutil
import struct
import subprocess
import sys
import time
from dataclasses import dataclass
from pathlib import Path

from . import ast as A

ROOT = Path(__file__).resolve().parent.parent
SDK = Path(os.environ.get("VULKAN_SDK", Path.home() / "VulkanSDK/1.4.363.0/macOS"))
SLANGC = Path(os.environ["SLANGC"]) if os.environ.get("SLANGC") else SDK / "bin/slangc"
SPIRV_VAL = SDK / "bin/spirv-val"
ICD = SDK / "share/vulkan/icd.d"
SLANGC_VERSION = None   # filled in lazily by cmd_fuzz / selftest
WORK = ROOT / "work"
THREADS = 64            # one input vector per thread
IN_WORDS = 9            # a: uint4, b: uint4, s: uint
TIMEOUT_S = 60

VK_PATHS = {
    "kosmickrisp": {"VK_DRIVER_FILES": str(ICD / "libkosmickrisp_icd.json")},
    "moltenvk": {"VK_DRIVER_FILES": str(ICD / "MoltenVK_icd.json")},
}
PATHS = ["metal", "kosmickrisp", "moltenvk"]

# Edge values make wraparound, sign-bit and all-ones cases common.
EDGES = [0, 1, 2, 3, 31, 32, 0x7FFFFFFF, 0x80000000, 0x80000001, 0xFFFFFFFE, 0xFFFFFFFF,
         0x55555555, 0xAAAAAAAA, 0x0000FFFF, 0xFFFF0000, 0x00010000]


# ------------------------------------------------------------------ kernel


def kernel_source(funcs: list[str]) -> str:
    """One compute kernel; thread t evaluates every function on input t."""
    lines = [
        "// generated by slang-difftest",
        "[[vk::binding(0, 0)]] StructuredBuffer<uint> inp;",
        "[[vk::binding(1, 0)]] RWStructuredBuffer<uint> outp;",
        f"static const uint N = {THREADS};",
        "",
    ]
    for i, body in enumerate(funcs):
        lines.append(f"uint4 f{i}(uint4 a, uint4 b, uint s) {{ return {body}; }}")
    lines += [
        "",
        "[shader(\"compute\")]",
        "[numthreads(64, 1, 1)]",
        "void main(uint3 tid : SV_DispatchThreadID)",
        "{",
        "    uint t = tid.x;",
        "    if (t >= N) return;",
        f"    uint4 a = uint4(inp[t*{IN_WORDS}+0], inp[t*{IN_WORDS}+1], inp[t*{IN_WORDS}+2], inp[t*{IN_WORDS}+3]);",
        f"    uint4 b = uint4(inp[t*{IN_WORDS}+4], inp[t*{IN_WORDS}+5], inp[t*{IN_WORDS}+6], inp[t*{IN_WORDS}+7]);",
        f"    uint s = inp[t*{IN_WORDS}+8];",
        "    uint4 r;",
    ]
    for i in range(len(funcs)):
        lines.append(f"    r = f{i}(a, b, s); "
                     f"outp[({i}u*N+t)*4u+0u] = r.x; outp[({i}u*N+t)*4u+1u] = r.y; "
                     f"outp[({i}u*N+t)*4u+2u] = r.z; outp[({i}u*N+t)*4u+3u] = r.w;")
    lines.append("}")
    return "\n".join(lines) + "\n"


def make_inputs(rng: random.Random) -> list[tuple]:
    """THREADS input tuples (a, b, s); thread 0 is all zeros, thread 1 all ones."""
    out = []
    for t in range(THREADS):
        if t == 0:
            words = [0] * IN_WORDS
        elif t == 1:
            words = [A.M32] * IN_WORDS
        else:
            words = [rng.choice(EDGES) if rng.random() < 0.5 else rng.getrandbits(32)
                     for _ in range(IN_WORDS)]
        out.append((tuple(words[0:4]), tuple(words[4:8]), words[8]))
    return out


def pack_inputs(inputs) -> bytes:
    return b"".join(struct.pack("<9I", *a, *b, s) for a, b, s in inputs)


# ------------------------------------------------------------------ steps


def slangc_version() -> str:
    p = subprocess.run([str(SLANGC), "-version"], capture_output=True, text=True)
    return (p.stdout.strip() or p.stderr.strip()).splitlines()[0] if (p.stdout or p.stderr) else "?"


def slangc_cmd(src: Path, target: str, out: Path) -> list[str]:
    return [str(SLANGC), str(src), "-target", target, "-entry", "main", "-stage", "compute", "-o", str(out)]


def cpp_check_cmd(cpp: Path) -> list[str]:
    return ["clang++", "-std=c++17", "-fsyntax-only", f"-I{SDK / 'include/slang'}", "-x", "c++", str(cpp)]


def kernel_signature(msl_text: str):
    """(kernel name, buffer index of `inp`, buffer index of `outp`) from slangc's MSL."""
    # The parameter list itself contains ")" (e.g. [[buffer(0)]]), so read up to the body's "{".
    m = re.search(r"\[\[kernel\]\]\s*void\s+(\w+)\s*\((.*?)\)\s*\{", msl_text, re.S)
    if not m:
        return None
    idx = {}
    for name in ("inp", "outp"):
        mm = re.search(rf"\b{name}\w*\s*\[\[buffer\((\d+)\)\]\]", m.group(2))
        if not mm:
            return None
        idx[name] = int(mm.group(1))
    return m.group(1), idx["inp"], idx["outp"]


@dataclass
class Compiled:
    ok: bool
    spv: Path | None = None
    msl: Path | None = None
    kernel_name: str = ""
    in_idx: int = -1
    out_idx: int = -1
    finding: dict | None = None


def run(cmd, env=None, timeout=TIMEOUT_S):
    t0 = time.monotonic()
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout,
                           env={**os.environ, **(env or {})})
        return p.returncode, p.stdout, p.stderr, time.monotonic() - t0
    except subprocess.TimeoutExpired:
        return "timeout", "", "", time.monotonic() - t0


def compile_batch(src_path: Path, spv_src: Path | None = None) -> Compiled:
    """slangc to SPIR-V and MSL. `spv_src` lets selftest feed a different
    source to the SPIR-V path only (fault injection)."""
    spv = src_path.with_suffix(".spv")
    msl = src_path.with_suffix(".metal")
    for target, out, src in (("spirv", spv, spv_src or src_path), ("metal", msl, src_path)):
        rc, _, err, _ = run(slangc_cmd(src, target, out))
        if rc != 0:
            kind = "slangc_crash" if (rc == "timeout" or (isinstance(rc, int) and rc < 0)
                                      or "internal" in err.lower()) else "slangc_reject"
            return Compiled(False, finding={"kind": kind, "target": target, "rc": rc,
                                            "stderr": err[-1500:]})
    rc, _, err, _ = run([str(SPIRV_VAL), str(spv)])
    if rc != 0:
        return Compiled(False, finding={"kind": "spirv_invalid", "stderr": err[-1500:]})

    # C++ (CPU target) compile oracle: slangc's C++ must at least compile.
    cpp = src_path.with_suffix(".cpp")
    rc, _, err, _ = run(slangc_cmd(src_path, "cpp", cpp))
    if rc != 0:
        return Compiled(False, finding={"kind": "slangc_reject", "target": "cpp", "rc": rc,
                                        "stderr": err[-1500:]})
    rc, _, err, _ = run(cpp_check_cmd(cpp))
    cpp_finding = None
    if rc != 0:
        errs = [ln for ln in err.splitlines() if "error:" in ln]
        cpp_finding = {"kind": "cpp_codegen_invalid", "errors": errs[:5]}

    sig = kernel_signature(msl.read_text())
    if not sig:
        return Compiled(False, finding={"kind": "harness_error", "msg": "could not parse MSL kernel signature"})
    return Compiled(True, spv, msl, sig[0], sig[1], sig[2], finding=cpp_finding)


def run_path(path: str, c: Compiled, in_bin: Path, out_words: int):
    out_bin = in_bin.with_name(f"out-{path}.bin")
    if out_bin.exists():
        out_bin.unlink()
    if path == "metal":
        cmd = [str(ROOT / "build/mtl_run"), str(c.msl), c.kernel_name, str(c.in_idx), str(c.out_idx),
               str(THREADS), str(in_bin), str(out_bin), str(out_words)]
        env = None
    else:
        cmd = [str(ROOT / "build/vk_run"), str(c.spv), str(THREADS), str(in_bin), str(out_bin),
               str(out_words)]
        env = VK_PATHS[path]
    rc, _, err, secs = run(cmd, env=env)
    if rc == 0 and out_bin.exists():
        data = out_bin.read_bytes()
        return "ok", list(struct.unpack(f"<{out_words}I", data)), secs, ""
    status = {"timeout": "hang", 4: "metal_reject"}.get(rc, "crash")
    return status, None, secs, err[-1500:]


def metal_per_function(texts, inputs, workdir: Path, mutate=None):
    """Metal outputs for each function compiled alone (MSL only); functions Metal
    rejects on their own stay None and are reported by the batch-level finding."""
    words = [None] * (len(texts) * THREADS * 4)
    in_bin = workdir / "in.bin"
    for i, body in enumerate(texts):
        d = workdir / f"single-{i}"
        d.mkdir(exist_ok=True)
        src, msl = d / "kernel.slang", d / "kernel.metal"
        # The single-function kernel names this function f0; outputs map back to slot i.
        src.write_text(kernel_source([body]))
        if run(slangc_cmd(src, "metal", msl))[0] != 0:
            continue
        if mutate and mutate.get("msl") and i == 0:
            msl.write_text(mutate["msl"](msl.read_text()))
        sig = kernel_signature(msl.read_text())
        if not sig:
            continue
        status, w, _, _ = run_path("metal", Compiled(True, None, msl, *sig), in_bin, THREADS * 4)
        if status == "ok":
            words[i * THREADS * 4:(i + 1) * THREADS * 4] = w
    return words


def reference(fn_asts, inputs) -> list[int]:
    out = [0] * (len(fn_asts) * THREADS * 4)
    for i, node in enumerate(fn_asts):
        for t, (a, b, s) in enumerate(inputs):
            v = A.evaluate(node, {"a": a, "b": b, "s": s})
            base = (i * THREADS + t) * 4
            out[base:base + 4] = list(v)
    return out


def triage(bad: set[str]) -> str:
    if bad == {"metal"}:
        return "Slang Metal codegen"
    if bad == {"kosmickrisp", "moltenvk"}:
        return "Slang SPIR-V codegen"
    if bad == {"moltenvk"}:
        return "SPIRV-Cross / MoltenVK"
    if bad == {"kosmickrisp"}:
        return "KosmicKrisp (Mesa)"
    if bad == set(PATHS):
        return "all GPU paths: Apple Metal compiler or the reference"
    return "mixed: " + "+".join(sorted(bad))


# ------------------------------------------------------------------ batch


def run_batch(seed: int, k: int, kinds, workdir: Path, mutate=None) -> dict:
    """Generate, compile, run and compare one batch. `mutate` is used only by
    selftest to plant faults: a dict with optional "msl" (str -> str, applied to
    the generated MSL) and "slang_for_spirv" (str -> str, applied to the Slang
    source fed to the SPIR-V path only)."""
    rng = random.Random(seed)
    gen = A.Gen(seed, kinds)
    fns = [gen.vec() for _ in range(k)]
    texts = [A.to_slang(f) for f in fns]
    src = kernel_source(texts)
    workdir.mkdir(parents=True, exist_ok=True)
    src_path = workdir / "kernel.slang"
    src_path.write_text(src)
    spv_src = None
    if mutate and mutate.get("slang_for_spirv"):
        spv_src = workdir / "kernel_spv.slang"
        spv_src.write_text(mutate["slang_for_spirv"](src))
    inputs = make_inputs(rng)
    in_bin = workdir / "in.bin"
    in_bin.write_bytes(pack_inputs(inputs))
    out_words = k * THREADS * 4

    t0 = time.monotonic()
    c = compile_batch(src_path, spv_src)
    compile_s = time.monotonic() - t0
    result = {"seed": seed, "k": k, "kinds": kinds or "all", "compile_s": round(compile_s, 3),
              "slangc": str(SLANGC), "slangc_version": SLANGC_VERSION, "findings": [], "paths": {}}
    if not c.ok:
        result["findings"].append({**c.finding, "source": str(src_path)})
        return result
    if c.finding:   # non-fatal: C++ output didn't compile; GPU paths still run
        result["findings"].append({**c.finding, "source": str(src_path)})
    if mutate and mutate.get("msl"):
        c.msl.write_text(mutate["msl"](c.msl.read_text()))

    ref = reference(fns, inputs)
    outs = {}
    for path in PATHS:
        status, words, secs, err = run_path(path, c, in_bin, out_words)
        result["paths"][path] = {"status": status, "secs": round(secs, 3)}
        if status != "ok":
            result["findings"].append({"kind": f"{path}_{status}", "stderr": err, "source": str(src_path)})
        if status == "metal_reject":
            # One rejected function must not hide silent miscompiles in the rest of
            # the batch: re-run every function on Metal on its own.
            words = metal_per_function(texts, inputs, workdir, mutate)
        outs[path] = words

    for i in range(k):
        bad, example = set(), None
        for path in PATHS:
            got = outs[path]
            if got is None:
                continue
            for t in range(THREADS):
                base = (i * THREADS + t) * 4
                if None in got[base:base + 4]:
                    continue   # this function was rejected by Metal; reported separately
                if got[base:base + 4] != ref[base:base + 4]:
                    bad.add(path)
                    if example is None:
                        a, b, s = inputs[t]
                        example = {"thread": t, "a": [hex(x) for x in a], "b": [hex(x) for x in b],
                                   "s": hex(s), "ref": [hex(x) for x in ref[base:base + 4]]}
                    example[path] = [hex(x) for x in got[base:base + 4]]
                    break
        if bad:
            result["findings"].append({
                "kind": "mismatch", "fn": i, "expr": texts[i], "size": A.size(fns[i]),
                "features": sorted(A.kinds_in(fns[i])), "bad_paths": sorted(bad),
                "layer": triage(bad), "example": example, "source": str(src_path),
            })
    return result


# ------------------------------------------------------------------ commands


def bucket(fd: dict) -> tuple:
    """Coarse root-cause grouping: value mismatches by the layer triage blames,
    C++ errors by the error text. One bug typically shows up as many findings."""
    if fd["kind"] == "mismatch":
        return ("mismatch", fd["layer"])
    if fd["kind"] == "cpp_codegen_invalid":
        e = (fd.get("errors") or [""])[0]
        return ("cpp_codegen_invalid", re.sub(r"^.*?error: ", "", e)[:110])
    return (fd["kind"],)


def cmd_fuzz(args):
    global SLANGC_VERSION
    SLANGC_VERSION = slangc_version()
    kinds = A.FAMILIES[args.family] if args.family != "all" else None
    stamp = time.strftime("%Y%m%d-%H%M%S")
    log = ROOT / f"results/raw-{stamp}-{args.family}.jsonl"
    log.parent.mkdir(exist_ok=True)
    totals = {"batches": 0, "functions": 0, "findings": 0}
    buckets = {}
    t0 = time.monotonic()
    print(f"slangc {SLANGC_VERSION} ({SLANGC})", flush=True)
    with log.open("w") as f:
        for bi in range(args.batches):
            seed = args.seed * 100003 + bi
            wd = WORK / f"{args.family}-{seed}"
            r = run_batch(seed, args.k, kinds, wd)
            f.write(json.dumps(r) + "\n")
            f.flush()
            totals["batches"] += 1
            totals["functions"] += args.k
            totals["findings"] += len(r["findings"])
            for fd in r["findings"]:
                buckets.setdefault(bucket(fd), []).append(seed)
                tag = fd.get("layer") or fd.get("kind")
                detail = fd.get("expr") or (fd.get("errors") or [""])[0] or fd.get("stderr", "")
                print(f"  [seed {seed}] {fd['kind']}: {tag} :: {detail[:160]}", flush=True)
            if not r["findings"] and not args.keep_work:
                shutil.rmtree(wd, ignore_errors=True)   # keep only batches worth reproducing
    secs = time.monotonic() - t0
    print(f"\n{totals['functions']} functions in {totals['batches']} batches, "
          f"{totals['findings']} findings in {len(buckets)} buckets, "
          f"{totals['functions'] / secs * 60:.0f} functions/min ({secs:.0f} s). Log: {log}")
    for key, seeds in sorted(buckets.items(), key=lambda kv: -len(kv[1])):
        print(f"  {len(seeds):4d} x {key}  (e.g. seed {seeds[0]})")


def swap_first_op_in(fn_index: int, old: str, new: str):
    """Replace the first `old` token inside function f<fn_index>'s body. Works on
    both the Slang source (`uint4 f0(...) { ... }`) and slangc's MSL, where the
    function is renamed to f0_0 and its body spans several lines."""
    head = re.compile(rf"\bf{fn_index}(?:_\d+)?\s*\([^)]*\)\s*\{{")

    def mutate(text: str) -> str:
        m = head.search(text)
        assert m, f"function f{fn_index} not found"
        body_end = text.index("}", m.end())
        body = text[m.end():body_end]
        assert old in body, f"{old!r} not in f{fn_index}"
        return text[:m.end()] + body.replace(old, new, 1) + text[body_end:]
    return mutate


def cmd_selftest(args):
    """The harness must (1) be clean on correct code, (2) catch planted
    faults in exactly one translation path and blame the right layer."""
    ok = True
    # 1. clean runs: arithmetic-only families must produce no findings.
    clean = run_batch(7, 16, A.FAMILIES["arith"], WORK / "selftest-clean")
    print(f"clean batch: {len(clean['findings'])} findings (want 0)")
    ok &= not clean["findings"]

    # Find a seed whose function 0 contains '^' so the fault has something to hit.
    seed = next(s for s in range(1000)
                if "^" in A.to_slang(A.Gen(s, A.FAMILIES["arith"]).vec()))
    expect = {
        "metal-only fault": ({"msl": swap_first_op_in(0, "^", "|")}, "Slang Metal codegen"),
        "spirv-only fault": ({"slang_for_spirv": swap_first_op_in(0, "^", "|")}, "Slang SPIR-V codegen"),
    }
    for name, (mutate, want_layer) in expect.items():
        r = run_batch(seed, 4, A.FAMILIES["arith"], WORK / f"selftest-{name.split()[0]}", mutate)
        layers = {fd.get("layer") for fd in r["findings"] if fd["kind"] == "mismatch"}
        fns = {fd.get("fn") for fd in r["findings"] if fd["kind"] == "mismatch"}
        good = layers == {want_layer} and fns == {0}
        ok &= good
        print(f"{name}: findings in fn {sorted(fns)}, blamed {sorted(layers)} -> {'PASS' if good else 'FAIL'}")
    print("SELFTEST", "PASS" if ok else "FAIL")
    sys.exit(0 if ok else 1)


def main():
    ap = argparse.ArgumentParser(prog="difftest")
    sub = ap.add_subparsers(dest="cmd", required=True)
    f = sub.add_parser("fuzz")
    f.add_argument("--batches", type=int, default=10)
    f.add_argument("--k", type=int, default=32)
    f.add_argument("--family", default="all", choices=["all", *A.FAMILIES])
    f.add_argument("--seed", type=int, default=1)
    f.add_argument("--keep-work", action="store_true", help="keep work/ dirs of batches with no findings")
    sub.add_parser("selftest")
    args = ap.parse_args()
    {"fuzz": cmd_fuzz, "selftest": cmd_selftest}[args.cmd](args)


if __name__ == "__main__":
    main()
